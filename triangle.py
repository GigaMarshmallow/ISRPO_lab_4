def area(a, h): 
    """
    Вычисляет площадь треугольника по длине стороны и высоте, проведённой к данной стороне.

    Параметры:
        a (float): длина стороны a
        h (float): длина высоты, опущенной к стороне a

    Возвращаемое значение:
        float: площадь треугольника

    Пример вызова:
        area(4, 5) -> 10
    """
    return a * h / 2 


def perimeter(a, b, c): 
    """
    Вычисляет периметр треугольника по заданным длинам сторон a, b и c.

    Параметры:
        a (float): длина стороны a
        b (float): длина стороны b
        c (float): длина стороны c

    Возвращаемое значение:
        float: периметр треугольника

    Пример вызова:
        perimeter(4, 5, 6) -> 15
    """
    return a + b + c 
